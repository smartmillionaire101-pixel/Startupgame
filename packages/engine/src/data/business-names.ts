const FEMALE = new Set<string>([
  ...MORE_FEMALE,
  ...Object.values(CITY_NAME_PARTS).flatMap((p) => p.female),
]);
const MALE = new Set<string>(Object.values(CITY_NAME_PARTS).flatMap((p) => p.male));
const TITLES = new Set(['Dr', 'Dr.', 'Alhaji', 'Hagg', 'Chief', 'Pa', 'Baba', 'Mzee', 'Uncle']);

/**
 * Best guess at someone's gender from their first name (for avatars only).
 * Unknown names fall back to a stable choice from the name itself.
 */
export function genderOfName(name: string): 'female' | 'male' {
  const words = name.split(/\s+/).filter(Boolean);
  for (const w of words) {
    if (FEMALE.has(w)) return 'female';
    if (MALE.has(w)) return 'male';
    if (!TITLES.has(w)) break;
  }
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
  return h % 2 === 0 ? 'female' : 'male';
}
