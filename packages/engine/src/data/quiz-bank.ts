/**
 * Wave 12 §A: the quiz night question bank. Every question is in English and
 * French; the first option is the right answer (each game shuffles the
 * options with its own seeded RNG, and the view never sends which one is
 * right until the question closes). Difficulty 1 (easy) to 3 (hard) sets how
 * often AI players know the answer.
 *
 * This file is read by the server only: the client never imports it.
 */
import type { MarketId } from './markets.js';
import type { QuizCategory } from '../games-types.js';

export { QUIZ_CATEGORIES, type QuizCategory } from '../games-types.js';

/** [question, right answer, wrong, wrong, wrong]. */
type Five = [string, string, string, string, string];

export interface BankQuestion {
  id: string;
  cat: QuizCategory;
  /** 1 easy … 3 hard. */
  diff: 1 | 2 | 3;
  /** City questions belong to one city. */
  city?: MarketId;
  en: Five;
  fr: Five;
}

const q = (
  id: string,
  cat: QuizCategory,
  diff: 1 | 2 | 3,
  en: Five,
  fr: Five,
  city?: MarketId,
): BankQuestion => ({ id, cat, diff, en, fr, ...(city ? { city } : {}) });

const g = (id: string, diff: 1 | 2 | 3, en: Five, fr: Five) => q(`g${id}`, 'general', diff, en, fr);
const b = (id: string, diff: 1 | 2 | 3, en: Five, fr: Five) =>
  q(`b${id}`, 'business', diff, en, fr);
const s = (id: string, diff: 1 | 2 | 3, en: Five, fr: Five) => q(`s${id}`, 'sport', diff, en, fr);
const m = (id: string, diff: 1 | 2 | 3, en: Five, fr: Five) => q(`m${id}`, 'music', diff, en, fr);
const c = (city: MarketId, n: number, diff: 1 | 2 | 3, en: Five, fr: Five) =>
  q(`c-${city}-${n}`, 'city', diff, en, fr, city);

