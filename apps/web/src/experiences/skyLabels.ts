/**
 * Wave 12: what you can name from a sky view, city by city: the famous
 * buildings, bridges, parks and neighbourhoods at their real places ([lat,
 * lon]). `h` is about how tall it stands (metres), so its name floats on top;
 * `area` marks a neighbourhood or a park (drawn smaller). Proper names, the
 * same in every language; `detail` is a line about it (English, translated).
 */
