const group = (kind: string) =>
  STREET.includes(kind) ? STREET : CAFE.includes(kind) ? CAFE : DINE;

/**
 * The style of a place to eat, or null if it isn't one (a bar, a club, a
 * shop). Deterministic: the same city, kind, name and id give the same place.
 */
export function foodStyleOf(v: {
  market: string;
  id: string;
  kind: string;
  name?: string;
}): FoodPlace | null {
  const kind = v.kind.toLowerCase();
  if (!isFoodPlaceKind(kind)) return null;
  const city = FOOD_STYLES[v.market] ?? [];
  const name = v.name ?? '';
  const g = group(kind);
  // 1. The name gives it away (a hint must suit the kind: no buka turns into fine dining).
  let s = city.find((c) => c.hint?.test(name) && c.kinds.includes(kind));
  // 2. The city's styles for the kind, by the id's hash.
  if (!s) {
    let pool = city.filter((c) => c.kinds.includes(kind) && !c.hintOnly);
    if (!pool.length) pool = city.filter((c) => c.kinds.includes(kind));
    if (!pool.length) pool = city.filter((c) => c.kinds.some((k) => g.includes(k)));
    if (!pool.length) pool = GENERIC.filter((c) => c.kinds.includes(kind));
    s = pool[hash(`${v.market}:${v.id}`) % pool.length];
  }
  if (!s) return null;
  const variant = hash(`${v.id}:look`) % 3;
  return { ...s, variant, tableCloth: s.cloth[variant % s.cloth.length]! };
}

/** Engine item ids that are a drink, whatever their energy. */
const DRINKS = /^(drink|tea|coffee|soft|juice)$/;

/**
 * The dish an engine item is at this place (an English key for tx), or null
 * to keep the item's own label. The meal that fills you most is the house
 * dish, the next one the second dish, a drink the house drink.
 */
export function dishOf(
  s: Pick<FoodStyle, 'dishes'>,
  item: { id: string; energy?: number; activity?: boolean },
  items: readonly { id: string; energy?: number; price: number; activity?: boolean }[],
): string | null {
  if (item.activity) return null;
  const isDrink = (i: { id: string; energy?: number }) => DRINKS.test(i.id) || (i.energy ?? 0) <= 2;
  if (isDrink(item)) return s.dishes.drink;
  const meals = items
    .filter((i) => !i.activity && !isDrink(i))
    .sort((a, b) => (b.energy ?? 0) - (a.energy ?? 0) || b.price - a.price);
  const rank = meals.findIndex((i) => i.id === item.id);
  return rank === 0 ? s.dishes.main : rank === 1 ? s.dishes.side : null;
}

