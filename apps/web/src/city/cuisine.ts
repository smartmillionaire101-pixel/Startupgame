/**
 * Places to eat of each city (player feedback: "All restaurants are the same.
 * Can we make different restaurants based on the different countries?").
 *
 * Every restaurant, café and street-food place gets a style from its city's
 * real food scene: a Lagos buka with pots of jollof and plastic chairs, a
 * Nairobi nyama choma yard, a Cairo koshary shop under lanterns, a Dubai
 * dining room with the towers in the window, a London curry house with a
 * tandoor. The style sets the cuisine, the menu's dish names (relabelling
 * the engine's items: same command, same price), and the room: walls, floor,
 * tables, kitchen, decor, lighting and how the sign is drawn. Price tiers
 * look different: 1 a street stall or canteen, 2 a casual sit-down place, 3
 * fine dining.
 *
 * Deterministic, from the venue alone: the name gives the style away when it
 * can ("Pepper Soup House", "Biryani", "Trattoria"), else the city's styles
 * for the kind are picked by a hash of the venue id. A per-venue variant
 * then shifts the colours so two places of one style still differ.
 *
 * All strings here are English keys translated with tx() (../i18n/fr/restaurants.ts).
 */
import { hash } from './contract';

export type FoodTier = 1 | 2 | 3;

/** The kitchen you see from the door. */
export type Kitchen =
  | 'pots' // big pots on a counter (a buka, a chop bar, a koshary shop)
  | 'grill' // a charcoal drum grill with skewers (suya, brochettes, kofta)
  | 'fire' // an open fire pit / braai (nyama choma, shisa nyama)
  | 'tandoor' // a clay oven (a curry house, a biryani house)
  | 'wok' // woks and bamboo steamers (dim sum, a noodle bar)
  | 'espresso' // a coffee bar and a pastry case
  | 'oven' // a wood-fired dome oven (a trattoria, a bakery)
  | 'pass' // an open kitchen pass under heat lamps (fine dining)
  | 'sushi' // a sushi counter with a fish case
  | 'spit'; // a vertical spit (shawarma, al pastor)

/** How people sit. */
export type Seating =
  | 'plastic' // plastic chairs and covered tables
  | 'bench' // long wooden tables and benches
  | 'bistro' // small wooden tables
  | 'cloth' // white tablecloths, candles, glasses
  | 'booth' // banquettes along the wall
  | 'floor'; // a majlis: low cushions round a low table

export type Decor =
  | 'string-lights'
  | 'lanterns'
  | 'paper-lanterns'
  | 'palms'
  | 'plants'
  | 'textile'
  | 'arches'
  | 'lattice'
  | 'tiles'
  | 'brick'
  | 'chalkboard'
  | 'bunting'
  | 'fan'
  | 'candles'
  | 'chandelier'
  | 'umbrellas'
  | 'papel-picado'
  | 'photos'
  | 'wine'
  | 'mirrors';

/** What the window looks out on. */
export type View = 'skyline' | 'nile' | 'sea' | 'bay' | 'hills' | 'street';

export type FoodFloor =
  | 'parquet'
  | 'parquet-dark'
  | 'tile'
  | 'marble'
  | 'carpet'
  | 'concrete'
  | 'checker'
  | 'stone'
  | 'sand'
  | 'oak'
  | 'cream';

export interface FoodStyle {
  /** Stable (tests, data attributes): `<city>-<style>`. */
  id: string;
  /** Translatable: "Nigerian". */
  cuisine: string;
  /** Translatable: the kind of place, "Buka", "Curry house". */
  label: string;
  tier: FoodTier;
  /** Business kinds it can be. */
  kinds: readonly string[];
  kitchen: Kitchen;
  seating: Seating;
  /** Open-air: a yard, a stall under an awning, a beach. */
  outdoor?: boolean;
  wall: string;
  floor: FoodFloor;
  floorTint?: string;
  /** Tables and counters (wood or plastic). */
  wood: string;
  /** Tablecloth, table cover or banquette: one per venue variant. */
  cloth: readonly string[];
  /** The light's colour. */
  light: string;
  /** The sign: background, letters. */
  sign: readonly [string, string];
  /** A band of pattern along the wall (kente, adire, tiles): two colours. */
  pattern?: readonly [string, string];
  decor: readonly Decor[];
  view?: View;
  /** Translatable dish names: the main meal, the second, the drink. */
  dishes: { main: string; side: string; drink: string };
  /** A name that gives this style away. */
  hint?: RegExp;
  /** Only when the name says so (an amala joint, a pupusería): never picked by chance. */
  hintOnly?: boolean;
}

export interface FoodPlace extends FoodStyle {
  /** 0–2: which of the style's cloths and how the room is turned. */
  variant: number;
  /** The table colour for this venue. */
  tableCloth: string;
}

